// ── Экранирование пользовательского текста перед вставкой в innerHTML ──
// Используется везде, где в разметку попадают данные посетителей (имя, текст
// отзыва и т.п.) — без этого было возможно хранимое XSS через форму отзыва.
// ── РАСПИСАНИЕ (единый источник — settings.contacts, см. backend/utils/hours.js) ──
// wstart/wend — Пн–Пт, weStart/weEnd — Сб–Вс, weOff — Сб–Вс выходной, slot — минут.
const RD_HOURS_DEFAULTS = { wstart: '09:00', wend: '21:00', weStart: '10:00', weEnd: '20:00', slot: 60 };
function rdToMin(v, d) {
  const m = String(v || d || '').match(/^(\d{1,2}):(\d{2})$/);
  return m ? Number(m[1]) * 60 + Number(m[2]) : rdToMin(d, '00:00');
}
function rdPad(t) { return String(Math.floor(t / 60)).padStart(2, '0') + ':' + String(t % 60).padStart(2, '0'); }
function rdSchedule(c) {
  c = c || {};
  const D = RD_HOURS_DEFAULTS;
  return {
    wk: { start: rdToMin(c.wstart, D.wstart), end: rdToMin(c.wend, D.wend) },
    we: { start: rdToMin(c.weStart, D.weStart), end: rdToMin(c.weEnd, D.weEnd), off: c.weOff === true },
    slot: Number(c.slot) > 0 ? Number(c.slot) : D.slot,
  };
}
// Часы работы на дату YYYY-MM-DD → { closed, start, end, slot }
function rdHoursForDate(c, date) {
  const n = rdSchedule(c);
  const dow = new Date(date + 'T00:00:00Z').getUTCDay();
  if (dow === 0 || dow === 6) return { closed: n.we.off, start: n.we.start, end: n.we.end, slot: n.slot };
  return { closed: false, start: n.wk.start, end: n.wk.end, slot: n.slot };
}
function rdHoursText(c) {
  const n = rdSchedule(c);
  const wk = rdPad(n.wk.start) + '–' + rdPad(n.wk.end);
  if (n.we.off) return 'Пн–Пт: ' + wk + ', Сб–Вс: выходной';
  const we = rdPad(n.we.start) + '–' + rdPad(n.we.end);
  return we === wk ? 'Ежедневно: ' + wk : 'Пн–Пт: ' + wk + ', Сб–Вс: ' + we;
}
// openingHoursSpecification для JSON-LD из тех же настроек
function rdOpeningSpec(c) {
  const n = rdSchedule(c);
  const spec = (days, a, b) => ({ '@type': 'OpeningHoursSpecification', dayOfWeek: days, opens: rdPad(a), closes: rdPad(b) });
  const wkDays = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday'];
  const weDays = ['Saturday', 'Sunday'];
  if (n.we.off) return [spec(wkDays, n.wk.start, n.wk.end)];
  if (n.we.start === n.wk.start && n.we.end === n.wk.end) return [spec(wkDays.concat(weDays), n.wk.start, n.wk.end)];
  return [spec(wkDays, n.wk.start, n.wk.end), spec(weDays, n.we.start, n.we.end)];
}

// ── РАЗМЕТКА ОТЗЫВОВ (schema.org) — только из РЕАЛЬНЫХ опубликованных отзывов ──
// Вызывается со страницы отзывов после загрузки списка. Если отзывов нет — рейтинг в разметку не попадает.
// Ничего не выдумываем: оценка и количество считаются по всем опубликованным, в review — до 10 последних.
function rdIsoDate(v) {
  const s = String(v || '').trim(); let m;
  if ((m = s.match(/^(\d{4})-(\d{2})-(\d{2})/))) return m[1] + '-' + m[2] + '-' + m[3];
  if ((m = s.match(/^(\d{1,2})\.(\d{1,2})\.(\d{4})/))) return m[3] + '-' + m[2].padStart(2, '0') + '-' + m[1].padStart(2, '0');
  return null;
}
function rdTrimText(t, max) {
  const s = String(t || '').replace(/\s+/g, ' ').trim();
  if (s.length <= max) return s;
  const cut = s.slice(0, max); const sp = cut.lastIndexOf(' ');
  return (sp > max * 0.6 ? cut.slice(0, sp) : cut) + '…';
}
function rdReviewsLD(list) {
  const tag = [...document.querySelectorAll('script[type="application/ld+json"]')].find(t => { try { return JSON.parse(t.textContent)['@type'] === 'AutomotiveBusiness'; } catch (e) { return false; } });
  if (!tag) return;
  let d; try { d = JSON.parse(tag.textContent); } catch (e) { return; }
  const valid = (Array.isArray(list) ? list : []).filter(r => r && r.name && r.text && Number.isInteger(Number(r.stars)) && Number(r.stars) >= 1 && Number(r.stars) <= 5);
  delete d.aggregateRating; delete d.review;
  if (valid.length) {
    const sum = valid.reduce((a, r) => a + Number(r.stars), 0);
    d.aggregateRating = { '@type': 'AggregateRating', ratingValue: (Math.round(sum / valid.length * 10) / 10).toFixed(1), reviewCount: valid.length, bestRating: '5', worstRating: '1' };
    d.review = valid.slice(0, 10).map(r => {
      const o = { '@type': 'Review', author: { '@type': 'Person', name: String(r.name).slice(0, 80) }, reviewRating: { '@type': 'Rating', ratingValue: String(Number(r.stars)), bestRating: '5', worstRating: '1' }, reviewBody: rdTrimText(r.text, 500) };
      const iso = rdIsoDate(r.date); if (iso) o.datePublished = iso;
      return o;
    });
  }
  tag.textContent = JSON.stringify(d);
}

function escapeHtml(str) {
  if (str === null || str === undefined) return "";
  return String(str)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

const menuButton = document.querySelector(".menu-toggle");
const mainNav = document.querySelector(".main-nav");

if (menuButton && mainNav) {
  // aria-expanded/aria-label — чтобы скринридер сообщал открыто ли меню,
  // а не только показывал одну и ту же надпись "Открыть меню" всегда.
  menuButton.setAttribute("aria-expanded", "false");
  menuButton.setAttribute("aria-controls", "main-nav");
  mainNav.id = mainNav.id || "main-nav";
  const setMenuOpen = (open) => {
    mainNav.classList.toggle("open", open);
    menuButton.classList.toggle("is-open", open);
    menuButton.setAttribute("aria-expanded", String(open));
    menuButton.setAttribute("aria-label", open ? "Закрыть меню" : "Открыть меню");
  };
  menuButton.addEventListener("click", () => {
    setMenuOpen(!mainNav.classList.contains("open"));
  });
  // Клик по пункту меню закрывает мобильное меню (иначе оно остаётся открытым при переходе)
  mainNav.querySelectorAll("a").forEach((a) => {
    a.addEventListener("click", () => setMenuOpen(false));
  });
  // Escape закрывает меню и возвращает фокус на кнопку — без этого
  // клавиатурный пользователь не мог свернуть открытое меню иначе как табом до конца списка.
  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape" && mainNav.classList.contains("open")) {
      setMenuOpen(false);
      menuButton.focus();
    }
  });
}

