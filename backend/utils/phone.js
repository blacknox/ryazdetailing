// utils/phone.js — приведение телефона к сравнимому виду.
// Разные посетители вводят один и тот же номер по-разному: +7 999 123-45-67,
// 89991234567, 9991234567 и т.п. Чтобы чёрный список реально работал, а не
// требовал точного совпадения форматирования, сравниваем по последним 10
// цифрам (стандартная длина российского номера без кода страны/восьмёрки).
function normalizePhone(phone) {
  const digits = String(phone || '').replace(/\D/g, '');
  return digits.slice(-10);
}

module.exports = { normalizePhone };
