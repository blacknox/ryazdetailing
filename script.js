// СИНХРОНИЗАЦИЯ КОНТАКТОВ И ТЕКСТОВ СТРАНИЦ С СЕРВЕРОМ
// Раньше читалось из localStorage (a_contacts / a_site_content) — правки
// в админке видел только сам администратор в своём браузере. Теперь оба
// набора данных приходят с сервера, поэтому их видят все посетители.
// ═══════════════════════════════════════════════════════════
(async function syncSettingsFromAPI() {
  const API_BASE = 'https://ryazdetailing-backend.onrender.com/api';
  try {
    const [contactsRes, contentRes] = await Promise.all([
      fetch(`${API_BASE}/settings/contacts`),
      fetch(`${API_BASE}/settings/site_content`),
    ]);

    // ── КОНТАКТЫ (телефон, email, адрес, часы, соцсети) ──
    if (contactsRes.ok) {
      const { value: contacts } = await contactsRes.json();
      if (contacts && Object.keys(contacts).length) {
        if (contacts.phone) {
          const clean = contacts.phone.replace(/[^\d+]/g, '');
          document.querySelectorAll('a[href^="tel:"]').forEach(a => {
            a.href = 'tel:' + clean;
            if (/^[\+\d\s()\-–]+$/.test(a.textContent.trim())) a.textContent = contacts.phone;
          });
        }
        if (contacts.email) {
          document.querySelectorAll('a[href^="mailto:"]').forEach(a => {
            a.href = 'mailto:' + contacts.email;
            if (a.textContent.includes('@')) a.textContent = contacts.email;
          });
        }
        if (contacts.vk) document.querySelectorAll('a[href*="vk.com"]').forEach(a => a.href = contacts.vk);
        if (contacts.tg) document.querySelectorAll('a[href*="t.me"], a[href*="telegram"]').forEach(a => a.href = contacts.tg);
        if (contacts.wa) document.querySelectorAll('a[href*="wa.me"], a[href*="whatsapp"]').forEach(a => a.href = contacts.wa);
        if (contacts.addr) document.querySelectorAll('[data-contact="addr"]').forEach(el => el.textContent = contacts.addr);
        // График и JSON-LD строим из структурированных полей — текст и разметка всегда совпадают
        const hoursText = rdHoursText(contacts);
        document.querySelectorAll('[data-contact="hours"]').forEach(el => el.textContent = hoursText);
        document.querySelectorAll('script[type="application/ld+json"]').forEach(tag => {
          try {
            const d = JSON.parse(tag.textContent);
            if (d && d.openingHoursSpecification) {
              d.openingHoursSpecification = rdOpeningSpec(contacts);
              tag.textContent = JSON.stringify(d);
            }
          } catch (e) { /* битый JSON-LD не должен ломать страницу */ }
        });
      }
    }

    // ── КОНТЕНТ СТРАНИЦ (заголовки, тексты, переопределённые в админке) ──
    if (contentRes.ok) {
      const { value: siteContent } = await contentRes.json();
      if (siteContent) {
        Object.keys(siteContent).forEach(id => {
          const el = document.querySelector('[data-content="' + id + '"]');
          if (el) el.textContent = siteContent[id];
        });
      }
    }
  } catch (e) {
    console.warn('syncSettingsFromAPI error:', e);
  }
})();

