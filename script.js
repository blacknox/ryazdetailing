// Раньше читалось из localStorage (a_privacy_data) — правки в админке
// видел только сам администратор. Подгружаем актуальный текст с сервера
// в момент открытия модалки (не блокируем загрузку страницы ради этого).
(function initPrivacyModalSync() {
  document.querySelectorAll('[data-modal="privacy"]').forEach(button => {
    button.addEventListener('click', async () => {
      try {
        const res = await fetch('/api/settings/privacy');
        if (!res.ok) return;
        const { value: pd } = await res.json();
        if (pd && pd.text) {
          const formatted = pd.text
            .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
            .replace(/\n\n/g, '</p><p>').replace(/\n/g, '<br>');
          if (typeof modalBody !== 'undefined' && modalBody) modalBody.innerHTML = '<p>' + formatted + '</p>';
        }
      } catch (e) { /* используем текст по умолчанию, уже показанный модалкой */ }
    });
  });
})();

// ── Баннер о cookie ──
// Сайт сейчас не использует cookie для отслеживания (см. privacy.html) —
// баннер подготовлен заранее, чтобы его не пришлось делать в спешке в день,
// когда на сайт добавят счётчик статистики (например, Яндекс.Метрику).
// Флаг согласия хранится в localStorage — это техническая необходимость для
// самого баннера ("не показывать повторно"), персональных данных не содержит.
(function initCookieBanner() {
  if (localStorage.getItem('cookie_consent_ack')) return;

  const banner = document.createElement('div');
  banner.className = 'cookie-banner';
  banner.setAttribute('role', 'region');
  banner.setAttribute('aria-label', 'Уведомление о cookie');
  banner.innerHTML = `
    <p>Мы используем технически необходимое хранение в браузере и можем в будущем использовать cookie для статистики посещений. Подробнее — в <a href="privacy.html">политике конфиденциальности</a>.</p>
    <button class="btn btn-primary cookie-banner-btn" type="button">Хорошо</button>
  `;
  document.body.appendChild(banner);

  const close = () => {
    localStorage.setItem('cookie_consent_ack', '1');
    banner.classList.remove('is-visible');
    setTimeout(() => banner.remove(), 300);
  };
  banner.querySelector('button').addEventListener('click', close);

  requestAnimationFrame(() => banner.classList.add('is-visible'));
})();
