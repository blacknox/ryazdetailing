// ── Счётчики статистики (about.html): считаем один раз при появлении ──
const statNumbers = document.querySelectorAll(".stat-item strong");
if (statNumbers.length && "IntersectionObserver" in window) {
  const parseTarget = (text) => {
    const m = text.match(/[\d.,]+/);
    if (!m) return null;
    return parseFloat(m[0].replace(",", "."));
  };
  const countObserver = new IntersectionObserver(
    (entries, obs) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        const el = entry.target;
        obs.unobserve(el);
        const original = el.textContent.trim();
        const target = parseTarget(original);
        if (target === null || window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
        const suffix = original.replace(/^[\d.,\s]+/, "");
        const isFloat = original.includes(",") || original.includes(".");
        const duration = 900;
        const start = performance.now();
        const step = (now) => {
          const p = Math.min(1, (now - start) / duration);
          const eased = 1 - Math.pow(1 - p, 3);
          const val = target * eased;
          el.textContent = (isFloat ? val.toFixed(1).replace(".", ",") : Math.round(val)) + suffix;
          if (p < 1) requestAnimationFrame(step);
          else el.textContent = original;
        };
        requestAnimationFrame(step);
      });
    },
    { threshold: 0.4 }
  );
  statNumbers.forEach((el) => countObserver.observe(el));
}

